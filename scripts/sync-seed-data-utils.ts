type CharacterAscensionFamilies = Record<
  string,
  {
    sliver: CharacterAscensionTier;
    fragment: CharacterAscensionTier;
    chunk: CharacterAscensionTier;
    gemstone: CharacterAscensionTier;
  }
>;

