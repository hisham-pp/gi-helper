  LOW,
  MEDIUM,
  HIGH,
  HIGHEST,
  INCOMPLETE,
  EXIT_INITIATED,
  PRESENT,
  ABSENT,
  HALF_DAY,
  WEEK_OFF,
  HOLIDAY,
  PAID_LEAVE,
  UNPAID_LEAVE,
  ON_LEAVE,
